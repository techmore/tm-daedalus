#!/usr/bin/env python3
"""Generate src/daedalus/static/css/elementary-overrides.css from app.css.

app.css hard-codes hundreds of light-theme colors. For every top-level rule this maps
each text, background and border color to an elementary role variable by luminance
and hue, so one dark/light token set recolors the whole portal. Re-run after editing
app.css:  python3 scripts/gen_elementary_overrides.py
"""
import colorsys
import re
from pathlib import Path

static = Path(__file__).resolve().parents[1] / "src/daedalus/static/css"
css = re.sub(r"/\*.*?\*/", "", (static / "app.css").read_text(), flags=re.S)

COLOR = re.compile(r"#([0-9a-fA-F]{8}|[0-9a-fA-F]{6}|[0-9a-fA-F]{3})\b|rgba?\(([^)]*)\)")


def parse(value):
    match = COLOR.search(value)
    if not match:
        return None
    if match.group(1):
        h = match.group(1)
        if len(h) == 3:
            h = "".join(c * 2 for c in h)
        r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
        a = int(h[6:8], 16) / 255 if len(h) == 8 else 1.0
    else:
        parts = [p.strip() for p in re.split(r"[,/ ]+", match.group(2).strip()) if p.strip()]
        if len(parts) < 3:
            return None
        try:
            r, g, b = (float(p.rstrip("%")) / (100 if p.endswith("%") else 255) for p in parts[:3])
            a = float(parts[3].rstrip("%")) / (100 if parts[3].endswith("%") else 1) if len(parts) > 3 else 1.0
        except ValueError:
            return None
    return r, g, b, a


def role(prop, rgba):
    r, g, b, a = rgba
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    hue = h * 360
    if a < 0.45:
        return None
    if prop == "color":
        if l > 0.86:
            return None  # white-ish text on a colored fill stays
        if s > 0.45 and 0.25 < l < 0.7:
            if hue < 25 or hue > 335:
                return "var(--e-bad)"
            if 25 <= hue < 70:
                return "var(--e-warn)"
            if 70 <= hue < 170:
                return "var(--e-ok)"
            return "var(--e-accent)"
        return "var(--e-text)" if l < 0.3 else "var(--e-text-2)" if l < 0.5 else "var(--e-text-3)"
    if prop == "bg":
        if l < 0.45:
            return None  # dark/saturated fills (buttons, badges) are handled by hand
        if s > 0.25 and l > 0.6:
            if hue < 25 or hue > 335:
                return "var(--e-bad-bg)"
            if 25 <= hue < 70:
                return "var(--e-warn-bg)"
            if 70 <= hue < 170:
                return "var(--e-ok-bg)"
            return "var(--e-accent-soft)"
        return "var(--e-surface)" if l > 0.965 else "var(--e-surface-2)"
    if prop == "border":
        return "var(--e-border)" if l > 0.5 else None
    return None


PROPS = {"color": "color", "background": "bg", "background-color": "bg", "border": "border", "border-color": "border",
         "border-top": "border", "border-bottom": "border", "border-left": "border", "border-right": "border"}
out = []
for selector, body in re.findall(r"(?m)^([^@{}\n][^{}]*)\{([^{}]*)\}", css):
    selector = selector.strip()
    if not selector or selector.startswith(("from", "to", "0%", "100%")):
        continue
    decls = []
    for decl in body.split(";"):
        if ":" not in decl:
            continue
        prop, value = (x.strip() for x in decl.split(":", 1))
        kind = PROPS.get(prop)
        if not kind or "gradient" in value or "var(" in value.split("#")[0] and kind != "border":
            continue
        rgba = parse(value)
        mapped = role(kind, rgba) if rgba else None
        if not mapped:
            continue
        if kind == "bg":
            decls.append(f"background-color:{mapped}")
        elif kind == "color":
            decls.append(f"color:{mapped}")
        else:
            side = prop.replace("border", "")
            decls.append(f"border{side}-color:{mapped}")
    if decls:
        prefixed = ",".join("html " + part.strip() for part in selector.split(","))
        out.append(f"{prefixed}{{{';'.join(decls)}}}")
header = "/* Generated by scripts/gen_elementary_overrides.py from app.css - do not edit. */\n"
(static / "elementary-overrides.css").write_text(header + "\n".join(out) + "\n")
print(len(out), "rules")
